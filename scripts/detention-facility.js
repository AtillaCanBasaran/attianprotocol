(function () {
    "use strict";

    var VERDICT_KEY = "attian.detention.verdict.v1";

    function readVerdict() {
        try {
            return JSON.parse(window.sessionStorage.getItem(VERDICT_KEY) || "null");
        } catch (error) {
            return null;
        }
    }

    function clearVerdict() {
        try { window.sessionStorage.removeItem(VERDICT_KEY); } catch (error) { /* No local record available. */ }
    }

    function safeReturnPath(value) {
        if (value === "/" || (typeof value === "string" && value.indexOf("/index.html") === 0)) return value;
        return typeof value === "string" && value.indexOf("/memory_node/attian/") === 0 && value.indexOf("/detentionfacility/") === -1
            ? value
            : "/memory_node/attian/";
    }

    function initFacility() {
        var access = document.getElementById("detentionAccessPanel");
        var transfer = document.getElementById("detentionTransferPanel");
        var clear = document.getElementById("detentionClearRecord");
        var returnLink = document.getElementById("detentionReturnLink");
        var requestEntry = document.getElementById("detentionRequestEntry");
        var doorStatus = document.getElementById("detentionDoorStatus");
        var verdict = readVerdict();
        var demoRequested = false;
        try {
            demoRequested = (window.location.hostname === "localhost" || window.location.hostname === "127.0.0.1")
                && new URLSearchParams(window.location.search).get("carnival-demo") === "1";
        } catch (error) { /* Old browsers retain the normal sealed route. */ }

        if (!verdict && demoRequested) {
            verdict = {
                caseId: "DEMO-M-00",
                status: "convicted",
                score: 0,
                sourcePath: "/memory_node/attian/"
            };
        }
        var caseFile = verdict && window.ATTIAN_DETENTION_CASES && window.ATTIAN_DETENTION_CASES[verdict.caseId];
        if (!caseFile && demoRequested) {
            caseFile = {
                id: "DEMO-M-00",
                title: "Local Carnival Systems Inspection",
                charge: "Authorized preview of an unauthorized recreational modification."
            };
        }
        var admitted = Boolean(verdict && verdict.status === "convicted" && caseFile);

        returnLink.href = safeReturnPath(verdict && verdict.sourcePath);
        returnLink.textContent = admitted ? "[ return to preserved page ]" : "[ return to navigator ]";

        if (!admitted) {
            var requests = 0;
            if (requestEntry) requestEntry.addEventListener("click", function () {
                requests += 1;
                var replies = [
                    "Administrator: Request denied. A referral is not generated by requesting a referral-only referral.",
                    "Administrator: Still sealed. The door has not developed uncertainty.",
                    "Administrator: Third request logged. Continued door percussion becomes its own case.",
                    "Administrator: Final warning. Step away from the disciplinary architecture."
                ];
                if (doorStatus) doorStatus.textContent = "REQUESTS FILED: " + requests + " // " + (replies[requests - 1] || "incident threshold reached");
                if (requests >= 5 && window.AttianDetentionCourt) {
                    requests = 0;
                    window.AttianDetentionCourt.openIncident("DTN-001", { id: "sealed-facility-door-bashing" });
                }
            });
            return;
        }

        access.hidden = true;
        transfer.hidden = false;
        clear.hidden = false;
        document.getElementById("detentionTransferTitle").textContent = caseFile.title;
        document.getElementById("detentionTransferCase").textContent = caseFile.id;
        document.getElementById("detentionTransferCharge").textContent = caseFile.charge;
        document.getElementById("detentionTransferScore").textContent = verdict.score + " / 5 findings accepted // CONVICTED";

        clear.addEventListener("click", function () {
            clearVerdict();
            window.location.href = returnLink.href;
        });

        if (window.AttianCarnival) {
            window.AttianCarnival.init({
                verdict: verdict,
                caseFile: caseFile,
                returnPath: returnLink.href,
                preview: demoRequested
            });
        }
    }

    if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", initFacility);
    else initFacility();
}());
